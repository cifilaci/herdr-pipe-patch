//! Collects what the executable carries into itself.
//!
//! The launcher is the whole tool in one file: the script, the patch, the
//! payload, the skill and the installers that put the skill in place. The
//! payload is a patched herdr-core for one version; the version is not written
//! into the source - a build script reads the payload folder and emits the
//! list, so the launcher carries whatever version was put in `tree`.

use std::fs;
use std::path::{Path, PathBuf};

/// The files the executable carries, besides the payload. The skill and the
/// two installers belong here: a person who copies this one file to another
/// machine should be able to install the skill there, not only patch the pipe.
const EXTRA: &[&str] = &[
    "herdr-pipe-patch.ps1",
    "README.md",
    "LICENSE",
    "install-skill.ps1",
    "install-skill-wsl.sh",
    "patches/herdr-core-pipe-extra-sids.patch",
    "scripts/probe-core.ps1",
    "skills/herdr-pipe-patch/SKILL.md",
    "assets/herdr-skill-wrapper.md",
    "assets/herdr-skill-wrapper-wsl.md",
    "assets/win-hc",
];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    // `tree` is the tree the executable carries, in the same shape as the
    // repository: the script at the top, the patch, the payload, the skill,
    // the installers and the assets the installers read.
    let assets = manifest.join("tree");
    let payload_root = assets.join("payload");

    let mut versions: Vec<String> = Vec::new();
    if let Ok(entries) = fs::read_dir(&payload_root) {
        for entry in entries.flatten() {
            if entry.path().is_dir() {
                versions.push(entry.file_name().to_string_lossy().to_string());
            }
        }
    }
    versions.sort();

    // An executable with no payload carries no patched core at all: it would
    // unpack a tool that cannot do anything. The build fails instead.
    if versions.is_empty() {
        panic!(
            "there is no payload in launcher/tree/payload: the executable would carry no \
             patched core at all. Copy the payload folder into launcher/tree, or build one \
             with the tool (build -Version <v>)."
        );
    }

    let mut out = String::from("// Generated by build.rs from assets. Do not edit.\n");

    // The payload: one patched core per version.
    out.push_str("pub const PAYLOAD_VERSIONS: &[&str] = &[");
    for (i, version) in versions.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!("\"{}\"", version));
    }
    out.push_str("];\n\n");

    for version in &versions {
        let key = version.replace(['-', '.', '+'], "_");
        let dir = payload_root.join(version);
        out.push_str(&format!(
            "const PAYLOAD_{key}_EXE: &[u8] = include_bytes!({});\n",
            literal(&dir.join("herdr-core.exe"))
        ));
        out.push_str(&format!(
            "const PAYLOAD_{key}_SHA: &str = include_str!({});\n",
            literal(&dir.join("herdr-core.exe.sha256"))
        ));
        out.push_str(&format!(
            "const PAYLOAD_{key}_BUILD: &str = include_str!({});\n",
            literal(&dir.join("BUILD.txt"))
        ));
    }

    out.push_str("\n/// The three files of one payload: the core, its checksum, how it was built.\n");
    out.push_str("pub fn payload_files(version: &str) -> (&'static [u8], &'static str, &'static str) {\n");
    out.push_str("    match version {\n");
    for version in &versions {
        let key = version.replace(['-', '.', '+'], "_");
        out.push_str(&format!(
            "        \"{version}\" => (PAYLOAD_{key}_EXE, PAYLOAD_{key}_SHA, PAYLOAD_{key}_BUILD),\n"
        ));
    }
    out.push_str("        _ => (&[], \"\", \"\"),\n");
    out.push_str("    }\n");
    out.push_str("}\n\n");

    // Everything else the executable carries. The constants come first: the
    // array below refers to them.
    let mut consts = String::new();
    let mut entries = String::new();
    let mut carried = 0;
    for (i, relative) in EXTRA.iter().enumerate() {
        let path = assets.join(relative);
        if !path.is_file() {
            // A warning would ship an executable that is missing a file the
            // README promises. The build fails instead.
            panic!(
                "the launcher will not carry {}: it is not in tree. \
                 Copy it into launcher/tree, or take it out of EXTRA.",
                relative
            );
        }
        consts.push_str(&format!(
            "const EXTRA_{i}: &[u8] = include_bytes!({});\n",
            literal(&path)
        ));
        entries.push_str(&format!(
            "    ({}, EXTRA_{i}),\n",
            format!("{:?}", relative.replace('\\', "/"))
        ));
        carried += 1;
    }
    out.push_str(&consts);
    out.push_str("\n/// The files beside the payload: the script, the patch, the skill and the installers.\n");
    out.push_str("pub const EXTRA_FILES: &[(&str, &[u8])] = &[\n");
    out.push_str(&entries);
    out.push_str("];\n");
    println!("cargo:warning=the launcher carries {carried} files besides the payload");

    // Everything in the tree has to be carried. A file that lands in the tree
    // but not in the executable would be in the released zip and missing from
    // the one-file form, and nothing would say so.
    let mut in_tree: Vec<String> = Vec::new();
    collect_files(&assets, &assets, &mut in_tree).expect("cannot read the tree");

    // The payload is carried as three files per version, so the payload part
    // of the tree is checked against those three: a fourth file there would
    // be in the released zip and missing from the one-file form.
    const PAYLOAD_FILES: [&str; 3] = ["herdr-core.exe", "herdr-core.exe.sha256", "BUILD.txt"];
    // Only version folders may sit in the payload: a loose file there is in
    // the released zip and in nobody's executable.
    if let Ok(entries) = fs::read_dir(&payload_root) {
        for entry in entries.flatten() {
            if !entry.path().is_dir() {
                panic!(
                    "payload/{} is a file, but only version folders may sit in the payload.",
                    entry.file_name().to_string_lossy()
                );
            }
        }
    }
    for version in &versions {
        let dir = payload_root.join(version);
        let mut in_payload: Vec<String> = Vec::new();
        collect_files(&dir, &dir, &mut in_payload).expect("cannot read the payload");
        for relative in &in_payload {
            if !PAYLOAD_FILES.contains(&relative.as_str()) {
                panic!(
                    "payload/{version}/{relative} is in the tree but the executable does not carry it. \
                     The payload carries the core, its checksum and BUILD.txt - take the file out \
                     of the tree, or carry it in the launcher.",
                    version = version
                );
            }
        }
        for expected in PAYLOAD_FILES {
            if !in_payload.iter().any(|p| p == expected) {
                panic!("payload/{version}/{expected} is missing: the payload is not complete.", version = version);
            }
        }
    }

    let mut carried_tree: Vec<String> = in_tree.clone();
    carried_tree.retain(|p| !p.starts_with("payload/"));
    for relative in &carried_tree {
        if !EXTRA.contains(&relative.as_str()) {
            panic!(
                "{} is in the tree but not in EXTRA, so the executable would not carry it. \
                 Add it to EXTRA, or take it out of the tree.",
                relative
            );
        }
    }
    for relative in EXTRA {
        if !carried_tree.iter().any(|p| p == relative) {
            panic!("{} is in EXTRA but not in the tree.", relative);
        }
    }

    let out_file = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("payloads.rs");
    fs::write(&out_file, out).expect("cannot write the generated file list");

    // Cargo's fingerprint for a directory is the newest file under it, so a
    // file that was taken out of the tree would not run this script again -
    // the build would fail later with a confusing error from include_bytes!.
    // Every file is named on its own, so taking one out changes the
    // fingerprint and the checks above run.
    for relative in &in_tree {
        println!("cargo:rerun-if-changed=tree/{relative}");
    }
    println!("cargo:rerun-if-changed=tree");

    // What the executable carries, written out for the release to check: the
    // package and the one-file form have to hold the same files, and the
    // release is where that is worth proving.
    let mut carried: Vec<String> = EXTRA.iter().map(|r| r.replace('\\', "/")).collect();
    for version in &versions {
        for file in PAYLOAD_FILES {
            carried.push(format!("payload/{version}/{file}"));
        }
    }
    carried.sort();
    let list_path = manifest.join("carried-files.txt");
    fs::write(&list_path, carried.join("\n") + "\n").expect("cannot write the carried file list");
    println!("cargo:warning=the executable carries {} files in all", carried.len());
}

/// Every file under `root`, as a path relative to it, with '/' separators.
fn collect_files(root: &Path, dir: &Path, out: &mut Vec<String>) -> std::io::Result<()> {
    let mut entries: Vec<_> = fs::read_dir(dir)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|e| e.path());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect_files(root, &path, out)?;
        } else {
            let relative = path
                .strip_prefix(root)
                .expect("a path under the root")
                .to_string_lossy()
                .replace('\\', "/");
            out.push(relative);
        }
    }
    Ok(())
}

/// A Rust string literal for a path, so `include_bytes!` can be given an
/// absolute one.
fn literal(path: &Path) -> String {
    let text = path.to_string_lossy();
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}
